"""Категории бизнеса и стартовые настройки бота для каждой.

В заготовке нет фактов о магазине (сроков, цен, адресов): только манера речи,
что уточнять у покупателя и когда звать менеджера. Доставку, оплату и скидки
магазин вписывает сам — при применении заготовки они сохраняются.
"""

from dataclasses import dataclass
from typing import Any

SHOP_OWNED_RULES = ("delivery", "payment", "discounts")


@dataclass(frozen=True)
class Niche:
    key: str
    title: str
    hint: str
    tone: str
    greeting: str
    handoff: str
    clarify: tuple[str, ...]
    address_form: str = "вы"

    def rules(self) -> dict[str, Any]:
        return {
            "address_form": self.address_form,
            "handoff": self.handoff,
            "custom": list(self.clarify),
        }


