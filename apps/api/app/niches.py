_BY_NAME = {name.casefold(): niche for niche in NICHES for name in (niche.key, niche.title)}


def find_niche(value: str | None) -> Niche | None:
    return _BY_NAME.get(value.strip().casefold()) if value else None


def preset_values(niche: Niche, current_rules: dict[str, Any] | None = None) -> dict[str, Any]:
    kept = {k: v for k, v in (current_rules or {}).items() if k in SHOP_OWNED_RULES and v}
    return {"tone": niche.tone, "greeting": niche.greeting, "rules": {**niche.rules(), **kept}}
